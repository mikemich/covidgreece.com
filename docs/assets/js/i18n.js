/** Look up a string and fill {placeholders}. Falls back to Greek, then the key. */
export function t(lang, key, vars = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.el[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

/** Translate every element that carries data-i18n / data-i18n-attr. */
export function applyTranslations(lang, root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.innerHTML = t(lang, el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(lang, key));
    });
  });
  document.title = t(lang, 'meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t(lang, 'meta.description'));
}
